"""
Canonical hypothesis definition.

Hypotheses are candidate explanations generated by Zoryn.

They are not facts.

They exist until confirmed, refined, or rejected by
subsequent observations.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any
from uuid import UUID

from .identifiers import new_id
from .time import now


@dataclass(frozen=True, slots=True)
class Hypothesis:
    """
    Immutable hypothesis.

    Parameters
    ----------
    hypothesis_type
        Logical type of the hypothesis.
    statement
        Human-readable description.
    confidence
        Estimated confidence.
    supporting_event_ids
        Events supporting this hypothesis.
    supporting_episode_ids
        Episodes supporting this hypothesis.
    metadata
        Optional additional information.
    """

    hypothesis_type: str
    statement: str

    confidence: float = 0.0

    supporting_event_ids: tuple[UUID, ...] = ()
    supporting_episode_ids: tuple[UUID, ...] = ()

    metadata: dict[str, Any] = field(default_factory=dict)

    created_at: datetime = field(default_factory=now)

    id: UUID = field(default_factory=new_id)